import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {parse} from 'node:path';
const read = path => readFile(path,'utf8');
const editions=JSON.parse(await read('content/ltc/index.json'));
const newest=editions.filter(e=>e.status==='published').sort((a,b)=>b.date.localeCompare(a.date)||b.revision-a.revision)[0];
const extra=JSON.parse(await read('content/ltc-extras/2026-10-06-delorean-r1.json'));
const ids=new Set(extra.sources.map(s=>s.id));
assert.equal(ids.size,extra.sources.length,'Source IDs are unique');
for(const section of extra.sections) for(const paragraph of section.paragraphs) for(const id of paragraph.sources) assert(ids.has(id),`Unknown source ${id}`);
for(const row of extra.registerRows) for(const id of row.sources) assert(ids.has(id),`Unknown table source ${id}`);
assert(extra.registerRows.every(r=>r.primary&&r.finding),'Every institutional comparison needs a scope/limitation');
assert.equal(extra.registerRows.find(r=>r.name==='Grayscale Litecoin Trust').effective,'2026-10-05','Preserve issuer effective date, separate from Register record');
for(const page of ['index.html','conversations/index.html']) {
 const html=await read(`dist/${page}`);
 assert(html.includes('aria-label="Current daily issue"'),`${page}: prominent daily navigation`);
 assert(html.includes(`editions/${newest.date}/index.html`),`${page}: current date destination`);
 assert(html.includes(newest.title),`${page}: actual daily title`);
 assert(html.includes('id="special-editions"'),`${page}: special shelf`);
 for(const slug of ['proof-of-birthday','charlie-lee','iykyk']) assert(html.includes(slug),`${page}: ${slug} discoverability`);
 assert(html.includes('aria-label="Previous daily editions"'),`${page}: distinct past daily area`);
}
const article=await read('dist/conversations/extras/litecoin-meets-delorean/index.html');
for(const s of extra.sections) assert(article.includes(`id="${s.id}"`));
for(const s of extra.sources) assert(article.includes(`id="source-${s.id}"`));
assert(article.includes('tabindex="0"'),'Comparison scroll region is keyboard reachable');
assert(article.includes('No speaker remarks'),'No unsupported Space reporting');
const canonical=await read('dist/conversations/editions/2026-10-06/index.html');
assert(canonical.includes('october-6-extra'));
const exact=await read('dist/conversations/editions/2026-10-06-r1/index.html');
assert(!exact.includes('october-6-extra'),'Exact morning revision is not rewritten with the extra');
assert.equal(await read('dist/data/ltc-extras/2026-10-06-delorean-r1.json'),await read('content/ltc-extras/2026-10-06-delorean-r1.json'));
const feed=await read('dist/conversations/feed.xml');
assert.equal(feed.split(`ltc:extra:${extra.id}`).length-1,1,'Extra has exactly one stable feed identity');
assert(!(await read('dist/conversations/daily.xml')).includes('ltc:extra:'),'Daily-only feed remains daily-only');
assert((await read('dist/sitemap-magazine.xml')).includes('/conversations/extras/litecoin-meets-delorean/'));
console.log('PASS: latest daily on both homes, three specials, past-day navigation, extra source/table provenance, immutable morning route, record, RSS and sitemap.');
